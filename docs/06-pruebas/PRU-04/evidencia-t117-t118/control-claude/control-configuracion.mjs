import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { ChromeBrowser } from './scripts/pruebas/cdp-helper.mjs';
const BASE = 'http://127.0.0.1:8127';
const esperar = ms => new Promise(r => setTimeout(r, ms));
const nav = new ChromeBrowser({ userDataDir: path.resolve('_chrome') });
await nav.start();
const p = await nav.newPage();
await p.connect();
await p.send('Network.enable');
const log = [];
p.on('Network.requestWillBeSent', d => { if (!/\.(js|css|png|svg|woff2?)/.test(d.request.url)) log.push('-> ' + d.request.method + ' ' + d.request.url.replace(BASE, '')); });
p.on('Network.responseReceived', d => { if (!/\.(js|css|png|svg|woff2?)/.test(d.response.url)) log.push('<- ' + d.response.status + ' ' + d.response.url.replace(BASE, '')); });
let responde = process.argv[2] === 'acepta';
p.on('Page.javascriptDialogOpening', async d => { log.push('DIALOGO ' + d.type + ' hasBrowserHandler=' + d.hasBrowserHandler); await p.send('Page.handleJavaScriptDialog', { accept: responde }); log.push('respondido ' + responde); });
const ev = e => p.evaluate(e);
execFileSync('php', ['artisan', 'cache:clear'], { encoding: 'utf8' });
await p.send('Network.clearBrowserCookies');
await p.goto(`${BASE}/login`); await esperar(400);
await ev(`(() => { document.querySelector('[name=email]').value='admin@wings.test'; document.querySelector('[name=password]').value='password'; document.querySelector('button[type=submit]').click(); })()`);
for (let i = 0; i < 40 && await ev('location.pathname').catch(() => '/login') === '/login'; i++) await esperar(300);
await p.goto(`${BASE}/configuraciones`); await esperar(800);
log.length = 0;
const clic = async sel => {
    await ev(`document.querySelector(${JSON.stringify(sel)}).scrollIntoView({block:'center', behavior:'instant'})`);
    await esperar(700);
    const r = JSON.parse(await ev(`(() => { const q=document.querySelector(${JSON.stringify(sel)}).getBoundingClientRect(); return JSON.stringify({x:q.x+q.width/2,y:q.y+q.height/2}); })()`));
    await p.send('Input.dispatchMouseEvent', { type: 'mouseMoved', x: r.x, y: r.y });
    for (const type of ['mousePressed', 'mouseReleased']) await p.send('Input.dispatchMouseEvent', { type, x: r.x, y: r.y, button: 'left', clickCount: 1 });
};
// Campo con cambio de verdad, tecleado.
await ev(`document.querySelector('.configuracion-form').dataset.marca='1'`);
await clic('.configuracion-form[data-marca] [name=valor]');
await esperar(200);
await ev(`(() => { const c=document.querySelector('.configuracion-form[data-marca]').elements.valor; c.select(); })()`);
await p.send('Input.insertText', { text: '12345' });
await esperar(200);
console.log('campo', await ev(`JSON.stringify({v:document.querySelector('.configuracion-form[data-marca]').elements.valor.value, type:document.querySelector('.configuracion-form[data-marca]').elements.valor.type, valido:document.querySelector('.configuracion-form[data-marca]').checkValidity()})`));
const { cookies } = await p.send('Network.getCookies');
for (const c of cookies) if (/session/.test(c.name)) await p.send('Network.deleteCookies', { name: c.name, url: BASE });
await clic('.configuracion-form[data-marca] button[type=submit]');
await esperar(3000);
console.log(log.join('\n'));
console.log('url', await ev('location.pathname'));
console.log('estado', await ev(`(() => { const f=document.querySelector('.configuracion-form[data-marca]'); if(!f) return 'sin form'; return JSON.stringify({boton:f.querySelector('button[type=submit]').disabled, campo:f.elements.valor.disabled, v:f.elements.valor.value, error:document.getElementById('error-'+f.dataset.clave)?.innerText, resumenOculto:document.getElementById('configuracion-error-resumen').hidden}); })()`));
console.log('aviso', (await ev('document.body.innerText')).includes('Tu sesión expiró'));
await p.close(); await nav.close();
